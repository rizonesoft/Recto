#!/usr/bin/env python3
"""Generate src/pdf/cff_data.inc: CFF's predefined data (Adobe Technical Note 5176, Appendices A to C; D01 T02 §29).

Reads src/pdf/pdf-encodings/cff-standard-data.txt (the 391 standard strings, the Expert and Expert Subset charsets and
the Expert encoding, transcribed; see that directory's README), checks it, and writes constexpr tables: the standard
strings by SID, each predefined charset as the SID of each glyph after .notdef, and the Expert encoding as the SID of
each code (0 for none). The ISOAdobe charset is SIDs 1 to 228 in order and the Standard encoding is the Annex D table
of glyph_names.inc, so neither needs a table here.

    python scripts/build-cff-data.py           # regenerate the table
    python scripts/build-cff-data.py --check   # exit 1 if the table is not what the transcription gives
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
DATA_PATH = REPO_ROOT / "src" / "pdf" / "pdf-encodings" / "cff-standard-data.txt"
OUT_PATH = REPO_ROOT / "src" / "pdf" / "cff_data.inc"
NAME = re.compile(r"[A-Za-z0-9._]+|\(\)")
COUNTS = {"Expert": 165, "ExpertSubset": 86}


class SourceError(ValueError):
    pass


def read(path: Path) -> tuple[list[str], dict[str, list[str]], dict[int, str]]:
    strings: list[str] = []
    charsets: dict[str, list[str]] = {"Expert": [], "ExpertSubset": []}
    encoding: dict[int, str] = {}
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        parts = line.split(" ")
        where = f"{path.name}:{number}"
        if parts[0] == "string" and len(parts) == 3:
            if int(parts[1]) != len(strings):
                raise SourceError(f"{where}: string {parts[1]} out of order")
            strings.append(parts[2])
        elif parts[0] == "charset" and len(parts) == 4 and parts[1] in charsets:
            if int(parts[2]) != len(charsets[parts[1]]) + 1:
                raise SourceError(f"{where}: charset {parts[1]} glyph {parts[2]} out of order")
            charsets[parts[1]].append(parts[3])
        elif parts[0] == "encoding" and len(parts) == 4 and parts[1] == "Expert":
            code = int(parts[2])
            if not 0 <= code <= 255 or code in encoding:
                raise SourceError(f"{where}: Expert encoding code {code} out of range or repeated")
            encoding[code] = parts[3]
        else:
            raise SourceError(f"{where}: not a string, charset or encoding line: {line!r}")
    return strings, charsets, encoding


def check(strings: list[str], charsets: dict[str, list[str]], encoding: dict[int, str]) -> dict[str, int]:
    if len(strings) != 391 or strings[0] != ".notdef" or len(set(strings)) != 391:
        raise SourceError("cff-standard-data.txt: not 391 unique standard strings starting .notdef")
    if not all(NAME.fullmatch(s) for s in strings):
        raise SourceError("cff-standard-data.txt: a standard string is not a plain name")
    sid = {s: i for i, s in enumerate(strings)}
    for name, glyphs in charsets.items():
        if len(glyphs) != COUNTS[name]:
            raise SourceError(f"cff-standard-data.txt: the {name} charset has {len(glyphs)} glyphs, not {COUNTS[name]}")
        missing = [g for g in glyphs if g not in sid]
        if missing:
            raise SourceError(f"cff-standard-data.txt: the {name} charset names non-standard strings: {missing[:5]}")
    if len(encoding) != 165 or any(n not in sid for n in encoding.values()):
        raise SourceError("cff-standard-data.txt: the Expert encoding is not 165 codes of standard strings")
    return sid


def render(strings: list[str], charsets: dict[str, list[str]], encoding: dict[int, str], sid: dict[str, int]) -> str:
    out = [
        "// Generated by scripts/build-cff-data.py from src/pdf/pdf-encodings/cff-standard-data.txt (Adobe Technical",
        "// Note 5176, Appendices A to C; D01 T02 section 29): do not edit.",
        "",
        "inline constexpr std::array<std::string_view, 391> kCffStandardStrings = {",
    ]
    for row in range(0, len(strings), 6):
        out.append("\t" + " ".join(f'"{s}",' for s in strings[row : row + 6]))
    out.append("};")
    for name in ("Expert", "ExpertSubset"):
        glyphs = charsets[name]
        out.append("")
        out.append(f"// The SID of each glyph after .notdef in the {name} charset.")
        out.append(f"inline constexpr std::array<uint16_t, {len(glyphs)}> kCff{name}Charset = {{")
        for row in range(0, len(glyphs), 16):
            out.append("\t" + " ".join(f"{sid[g]}," for g in glyphs[row : row + 16]))
        out.append("};")
    out.append("")
    out.append("// The SID of each code in the Expert encoding, 0 for none.")
    out.append("inline constexpr std::array<uint16_t, 256> kCffExpertEncoding = {")
    codes = [sid[encoding[c]] if c in encoding else 0 for c in range(256)]
    for row in range(0, 256, 16):
        out.append("\t" + " ".join(f"{v}," for v in codes[row : row + 16]))
    out.append("};")
    return "\n".join(out) + "\n"


def generate(path: Path) -> str:
    strings, charsets, encoding = read(path)
    return render(strings, charsets, encoding, check(strings, charsets, encoding))


def write_atomic(path: Path, text: str) -> None:
    tmp = path.with_name(path.name + ".tmp")
    with open(tmp, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.replace(tmp, path)
    if path.read_text(encoding="utf-8") != text:
        raise OSError(f"{path}: read back differs from what was written")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the table is not what the transcription gives")
    parser.add_argument("--data", type=Path, default=DATA_PATH, help=argparse.SUPPRESS)
    parser.add_argument("--out", type=Path, default=OUT_PATH, help=argparse.SUPPRESS)
    args = parser.parse_args(argv)
    try:
        text = generate(args.data)
    except (SourceError, OSError, ValueError) as exc:
        print(f"build-cff-data: {exc}", file=sys.stderr)
        return 1
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.exists() else None
        if current != text:
            print(f"build-cff-data: {args.out} is out of date; run python scripts/build-cff-data.py", file=sys.stderr)
            return 1
        print(f"build-cff-data: {args.out.name} is current")
        return 0
    write_atomic(args.out, text)
    print(f"build-cff-data: wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
